namespace
{
    bool Same(const MPL::PluginIndex::Result& a_left, const MPL::PluginIndex::Result& a_right)
    {
        return a_left.editorIDs == a_right.editorIDs && a_left.placements.size() == a_right.placements.size() &&
            std::ranges::all_of(a_left.placements, [&](const auto& a_entry)
            {
                const auto found = a_right.placements.find(a_entry.first);
                return found != a_right.placements.end() && found->second.reference == a_entry.second.reference &&
                    found->second.base == a_entry.second.base && found->second.cell == a_entry.second.cell &&
                    found->second.deleted == a_entry.second.deleted;
            });
    }

    int Verify(const int argc, wchar_t** argv)
    {
        using namespace MPL;
        using Clock = std::chrono::steady_clock;
        VanillaIndex::Catalog catalog;
        for (int index = 2; index < argc; ++index)
        {
            const std::filesystem::path path(argv[index]);
            std::ifstream input(path, std::ios::binary);
            if (!input) throw std::runtime_error("Verification source is unavailable");
            const auto lookup = catalog.Acquire(path.filename().string(), std::filesystem::file_size(path), input);
            if (!lookup.data) throw std::runtime_error("Verification fingerprint not recognized: " + lookup.reason);
            std::unordered_set<RE::FormID> exteriors, excluded;
            for (const auto& placement : lookup.data->placements)
            {
                if (placement.cell % 3 == 0) exteriors.insert(placement.cell);
                if (placement.cell % 5 == 0) excluded.insert(placement.cell);
            }
            double scannedMs = 0, appliedMs = 0;
            for (int mode = 0; mode < 4; ++mode)
            {
                PluginIndex::BuildOptions options;
                options.indexStaticEditorIDs = true;
                std::unordered_map<RE::FormID, PluginIndex::Placement> winners;
                if (mode == 1)
                {
                    options.skipExteriorCells = true;
                    options.excludedCells = excluded;
                    options.retainPlacement = [](RE::FormID, const RE::FormID a_base, RE::FormID) { return a_base % 17 == 0; };
                    for (const auto& placement : lookup.data->placements)
                        if (placement.reference % 11 == 0) winners.emplace(placement.reference, placement);
                }
                if (mode == 2) options.indexReferences = false;
                if (mode == 3) { options.indexReferences = false; options.indexStaticEditorIDs = false; }
                PluginIndex::Result scanned, applied;
                auto started = Clock::now();
                if (!PluginIndex::Testing::Parse(path, options, scanned, winners, exteriors))
                    throw std::runtime_error("Verification streaming parse failed");
                scannedMs += std::chrono::duration<double, std::milli>(Clock::now() - started).count();
                started = Clock::now();
                if (!PluginIndex::Testing::ApplyDataset(*lookup.data, options, applied, winners, exteriors) || !Same(scanned, applied))
                    throw std::runtime_error("Embedded/streaming result mismatch in verification mode " + std::to_string(mode));
                appliedMs += std::chrono::duration<double, std::milli>(Clock::now() - started).count();
            }
            std::cout << path.string() << " | 4 equivalence modes passed | validation=" << lookup.validationMs
                      << "ms decode=" << lookup.decodeMs << "ms | all modes stream=" << scannedMs << "ms apply=" << appliedMs << "ms\n";
        }
        return 0;
    }
}

int wmain(const int argc, wchar_t** argv)
{
    try
    {
        spdlog::set_level(spdlog::level::off);
        if (argc >= 3 && std::wstring_view(argv[1]) == L"--verify") return Verify(argc, argv);
        if (argc < 4 || std::wstring_view(argv[1]) != L"--output")
        {
            std::cerr << "Usage: GenerateVanillaIndex --output directory master.esm [...]\n"
                         "       GenerateVanillaIndex --verify master.esm [...]\n";
            return 2;
        }
        using namespace MPL;
        const std::filesystem::path root(argv[2]);
        std::filesystem::create_directories(root);
        std::ofstream manifest(root / "Manifest.inc"), resources(root / "Resources.rc.in");
        if (!manifest || !resources) throw std::runtime_error("Could not create generated manifest");
        manifest << "// Generated by GenerateVanillaIndex.\nstatic constexpr Descriptor kDescriptors[] = {\n";
        resources << "// Generated by GenerateVanillaIndex.\n";
        nlohmann::ordered_json report = nlohmann::ordered_json::array();
        std::map<std::string, std::uint32_t> dataResources;
        std::unordered_set<std::string> fingerprints;
        std::uint32_t nextResource = 20000;
        for (int index = 3; index < argc; ++index)
        {
            const std::filesystem::path path(argv[index]);
            const auto name = path.filename().string();
            if (!VanillaIndex::IsVanillaMaster(name)) throw std::runtime_error("Only vanilla master filenames are supported");
            const auto length = std::filesystem::file_size(path);
            std::ifstream input(path, std::ios::binary);
            if (!input) throw std::runtime_error("Could not open source master");
            const auto fingerprint = VanillaIndex::SHA256(input, length);
            input.close();
            if (!fingerprints.insert(name + fingerprint).second)
            {
                std::cout << name << " identical source already registered\n";
                continue;
            }
            PluginIndex::BuildOptions options;
            options.indexStaticEditorIDs = true;
            std::vector<RE::FormID> order;
            options.retainPlacement = [&](const RE::FormID a_reference, RE::FormID, RE::FormID)
            { order.push_back(a_reference); return true; };
            PluginIndex::Result parsed;
            if (!PluginIndex::Testing::Parse(path, options, parsed, {}))
                throw std::runtime_error("Source master did not pass the production parser");
            if (order.size() != parsed.referencesRead || order.size() != parsed.placements.size())
                throw std::runtime_error("Source has duplicate or unresolved references; refusing an ambiguous snapshot");
            VanillaIndex::Dataset data;
            data.placements.reserve(order.size());
            for (const auto form : order) data.placements.push_back(parsed.placements.at(form));
            for (const auto& entry : parsed.editorIDs) data.editorIDs.push_back(entry);
            std::ranges::sort(data.editorIDs, {}, &std::pair<std::uint32_t, std::string>::first);
            const auto encoded = VanillaIndex::Encode(data);
            const auto dataHash = VanillaIndex::SHA256(encoded);
            auto canonical = data;
            std::ranges::sort(canonical.placements, {}, &PluginRecords::Placement::reference);
            const auto semanticHash = VanillaIndex::SHA256(VanillaIndex::Encode(canonical));
            const auto [entry, added] = dataResources.emplace(dataHash, nextResource);
            std::size_t packedBytes = 0;
            if (added)
            {
                ++nextResource;
                const auto packed = VanillaIndex::Compress(encoded);
                packedBytes = packed.size();
                const auto filename = "table-" + dataHash + ".vindex";
                std::ofstream output(root / filename, std::ios::binary);
                output.write(reinterpret_cast<const char*>(packed.data()), static_cast<std::streamsize>(packed.size()));
                output.close();
                if (!output) throw std::runtime_error("Could not write generated vanilla index");
                resources << entry->second << " RCDATA \"@CMAKE_CURRENT_SOURCE_DIR@/assets/VanillaIndex/" << filename << "\"\n";
            }
            manifest << "    {\"" << name << "\", " << length << "ULL, \"" << fingerprint << "\", "
                     << entry->second << ", " << encoded.size() << "},\n";
            report.push_back({{"source", path.string()}, {"plugin", name}, {"file_bytes", length},
                {"file_sha256", fingerprint}, {"dataset_sha256", dataHash}, {"semantic_sha256", semanticHash},
                {"references", data.placements.size()}, {"static_editor_ids", data.editorIDs.size()},
                {"unpacked_bytes", encoded.size()}, {"new_resource_bytes", packedBytes}, {"resource", entry->second}});
            std::cout << name << " refs=" << data.placements.size() << " statics=" << data.editorIDs.size()
                      << " semantic=" << semanticHash << " resource=" << entry->second << '\n';
        }
        manifest << "};\n";
        manifest.close(); resources.close();
        if (!manifest || !resources) throw std::runtime_error("Could not finish generated manifest");
        std::ofstream output(root / "Generation.json");
        output << report.dump(2) << '\n';
        if (!output) throw std::runtime_error("Could not write generation report");
        std::cout << "Generated " << fingerprints.size() << " recognized files and " << dataResources.size() << " embedded datasets\n";
        return 0;
    }
    catch (const std::exception& error)
    {
        std::cerr << "Generation failed: " << error.what() << '\n';
        return 1;
    }
}
